	var lang = (new URLSearchParams(location.search).get("lang") || "").toLowerCase();
	window.DSI_LANG = lang === "hi" ? "hi" : "en";
	if (window.DSI_LANG !== "hi" || !window.WEDDING_HI) return;

	function merge(base, over) {
		if (!over) return base;
		var out = Array.isArray(base) ? base.slice() : Object.assign({}, base);
		Object.keys(over).forEach(function (key) {
			var a = base[key], b = over[key];
			if (b && typeof b === "object" && !Array.isArray(b) && a && typeof a === "object" && !Array.isArray(a)) {
				out[key] = merge(a, b);
			} else {
				out[key] = b;
			}
		});
		return out;
	}

	window.WEDDING = merge(window.WEDDING, window.WEDDING_HI);
	document.documentElement.lang = "hi-IN";
	document.documentElement.setAttribute("data-lang", "hi");
